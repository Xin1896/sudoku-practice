export const PUZZLES = Object.freeze(
  PUZZLE_DATA.map((entry) => Object.freeze(entry)),
);

export function getPuzzlesByDifficulty(difficulty) {
  return PUZZLES.filter((entry) => entry.difficulty === difficulty);
}

export function choosePuzzle(
  difficulty,
  completedPuzzleIds = [],
  random = Math.random,
) {
  const puzzles = getPuzzlesByDifficulty(difficulty);
  if (puzzles.length === 0) {
    return null;
  }

  let completed;
  try {
    completed = new Set(completedPuzzleIds ?? []);
  } catch {
    completed = new Set();
  }

  const unfinished = puzzles.filter((entry) => !completed.has(entry.id));
  const candidates = unfinished.length > 0 ? unfinished : puzzles;
  const randomValue = Number(random());
  const boundedValue = Number.isFinite(randomValue)
    ? Math.min(Math.max(randomValue, 0), 1 - Number.EPSILON)
    : 0;
  return candidates[Math.floor(boundedValue * candidates.length)];
}
